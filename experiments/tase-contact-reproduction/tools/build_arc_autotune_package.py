#!/usr/bin/env python3
"""Build a current-controller TP triplet for the mature Step4d arc law.

This package preserves the historical deterministic contact search and circle
geometry.  Candidate fields only replace the bounded post-latch normal
admittance terms; the target force, safety guards, path and attitude limits
remain fixed unless explicitly represented in the candidate receipt.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
from pathlib import Path
from typing import Any

from build_step4e_p0p1_programs import build_urp
from step5d_autotune_v4_r012.controller_triplet import validate_urscript_block_balance


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "programs/step4abcd/step4d_circle_detsearch_attitude_v1.script"
DEFAULT_BASENAME = "step4d_circle_autotune_v1"
CONTROLLER_DIR = "/programs/andyl/kunwei/step4"
SOURCE_ID = "STEP4D_DETSEARCH_SIGNED_FZ_ATTITUDE_MATURE_V1"
PATH_ID = "STEP4D_CIRCLE_MIDDLE_HALF_REFERENCE_FULL_CIRCLE_V1"

DEFAULT_CANDIDATE: dict[str, Any] = {
    "normal_velocity_p_gain": 0.0006,
    "normal_velocity_i_gain": 0.00008,
    "normal_filter_alpha": 0.70,
    "integral_error_limit_n_s": 10.0,
    "target_force_abs_n": 5.0,
    "tangent_speed_m_s": 0.005,
    "circle_xy_p_gain_m_s_per_m": 3.0,
    "circle_xy_velocity_limit_m_s": 0.003,
    "angular_velocity_limit_rad_s": 0.030,
    "attitude_force_gain_rad_s": 0.040,
    "attitude_torque_gain_rad_s_per_nm": 0.050,
    "attitude_filter_alpha": 0.20,
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _finite_candidate(raw: dict[str, Any]) -> dict[str, float]:
    candidate = dict(DEFAULT_CANDIDATE)
    candidate.update(raw)
    names = tuple(DEFAULT_CANDIDATE)
    out: dict[str, float] = {}
    for name in names:
        value = float(candidate[name])
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError(f"candidate {name} is not finite")
        out[name] = value
    bounds = {
        "normal_velocity_p_gain": (0.00005, 0.003),
        "normal_velocity_i_gain": (0.0, 0.0005),
        "normal_filter_alpha": (0.0, 1.0),
        "integral_error_limit_n_s": (0.0, 20.0),
        "target_force_abs_n": (1.0, 5.0),
        "tangent_speed_m_s": (0.001, 0.008),
        "circle_xy_p_gain_m_s_per_m": (0.5, 6.0),
        "circle_xy_velocity_limit_m_s": (0.0005, 0.004),
        "angular_velocity_limit_rad_s": (0.005, 0.030),
        "attitude_force_gain_rad_s": (0.0, 0.10),
        "attitude_torque_gain_rad_s_per_nm": (0.0, 0.10),
        "attitude_filter_alpha": (0.0, 1.0),
    }
    for name, (lo, hi) in bounds.items():
        if not lo <= out[name] <= hi:
            raise ValueError(f"candidate {name}={out[name]} outside [{lo}, {hi}]")
    if out["target_force_abs_n"] != 5.0:
        raise ValueError("live arc target force is fixed at 5 N")
    # Keep the live safety envelope independent of tuning; a candidate cannot
    # buy feasibility by changing the path or guard constants.
    if out["angular_velocity_limit_rad_s"] > 0.030:
        raise ValueError("candidate angular limit exceeds mature Step4d guard")
    return out


def _replace_once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"expected one source occurrence for {old!r}, found {count}")
    return text.replace(old, new, 1)


def build(output: Path, *, basename: str = DEFAULT_BASENAME, candidate: dict[str, Any] | None = None) -> dict[str, Any]:
    if not re.fullmatch(r"[A-Za-z0-9_]+", basename):
        raise ValueError("basename must be an ASCII controller program name")
    values = _finite_candidate(candidate or {})
    source_text = SOURCE.read_text(encoding="utf-8")
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ_ARC_AUTOTUNE_V1")
    body = source_text
    body = body.replace("step4d_circle_detsearch_attitude_v1", basename)
    body = re.sub(r"^# VERSION: .*?$", f"# VERSION: {stamp}", body, flags=re.M)
    body = re.sub(r"^# GENERATED_AT_LOCAL: .*?$", "# GENERATED_AT_LOCAL: generated by build_arc_autotune_package.py", body, flags=re.M)
    replacements = {
        "local normal_velocity_p_gain = 0.0006": f"local normal_velocity_p_gain = {values['normal_velocity_p_gain']:.12g}",
        "local normal_velocity_i_gain = 0.00008": f"local normal_velocity_i_gain = {values['normal_velocity_i_gain']:.12g}",
        "local normal_filter_alpha = 0.70": f"local normal_filter_alpha = {values['normal_filter_alpha']:.12g}",
        "local integral_error_limit_n_s = 10.0": f"local integral_error_limit_n_s = {values['integral_error_limit_n_s']:.12g}",
        "local target_force_abs_default_n = 5.0": f"local target_force_abs_default_n = {values['target_force_abs_n']:.12g}",
        "local tangent_speed_m_s = 0.005": f"local tangent_speed_m_s = {values['tangent_speed_m_s']:.12g}",
        "local circle_xy_p_gain_m_s_per_m = 3.0": f"local circle_xy_p_gain_m_s_per_m = {values['circle_xy_p_gain_m_s_per_m']:.12g}",
        "local circle_xy_velocity_limit_m_s = 0.003": f"local circle_xy_velocity_limit_m_s = {values['circle_xy_velocity_limit_m_s']:.12g}",
        "local angular_velocity_limit_rad_s = 0.030": f"local angular_velocity_limit_rad_s = {values['angular_velocity_limit_rad_s']:.12g}",
        "local attitude_force_gain_rad_s = 0.040": f"local attitude_force_gain_rad_s = {values['attitude_force_gain_rad_s']:.12g}",
        "local attitude_torque_gain_rad_s_per_nm = 0.050": f"local attitude_torque_gain_rad_s_per_nm = {values['attitude_torque_gain_rad_s_per_nm']:.12g}",
        "local attitude_filter_alpha = 0.20": f"local attitude_filter_alpha = {values['attitude_filter_alpha']:.12g}",
    }
    for old, new in replacements.items():
        body = _replace_once(body, old, new)
    body = body.replace(
        "# Step4d contact circle v1:",
        "# Current arc autotune candidate: mature Step4d deterministic-search + signed-Fz attitude law.",
        1,
    )
    body = body.replace(
        "# The first 0.10 s of circle control uses 10 ms speedl holds, then circle control\n",
        "# The first 0.10 s of circle control uses 10 ms speedl holds, then circle control\n",
        1,
    )
    validate_urscript_block_balance(body)
    for forbidden in ("zero_ftsensor(", "set_tcp(", "set_payload(", "read_input_integer_register("):
        if forbidden in body:
            raise ValueError(f"arc candidate contains forbidden side effect: {forbidden}")
    output.mkdir(parents=True, exist_ok=False)
    txt = (
        "TASE arc autotune candidate\n"
        f"Program: {basename}\n"
        f"Version: {stamp}\n"
        f"Controller directory: {CONTROLLER_DIR}\n"
        f"Control law identity: {SOURCE_ID}\n"
        f"Path identity: {PATH_ID}\n"
        "Source geometry: middle half of straight-line reference, one full circle\n"
        "Normal error: signed Fz target error; force norm is protection/diagnostic only\n"
        "Search: deterministic far/near downward search, no pre-contact admittance\n"
        "Live target force: 5 N; candidate bounds are enforced by the builder\n"
    )
    (output / f"{basename}.script").write_text(body, encoding="utf-8")
    (output / f"{basename}.txt").write_text(txt, encoding="utf-8")
    (output / f"{basename}.urp").write_bytes(build_urp(body, basename, CONTROLLER_DIR))
    binding = {
        "schema": "tase_arc_autotune_candidate_v1",
        "basename": basename,
        "stamp": stamp,
        "controller_directory": CONTROLLER_DIR,
        "source": str(SOURCE),
        "source_sha256": _sha256(SOURCE),
        "law_identity": SOURCE_ID,
        "path_identity": PATH_ID,
        "candidate": values,
        "fixed_safety": {
            "normal_guard_n": 20.0,
            "force_norm_guard_n": 50.0,
            "torque_guard_nm": 0.6,
            "sensor_stale_s": 0.1,
        },
        "metric_policy": {
            "target": "signed_normal_force_error_from_Fz; force_norm_is_diagnostic",
            "partial_path": "compute_and_mark_partial; never silently promote to full_path",
            "formal_full_path": "progress reaches path_length_m within 0.5 percent and stage25 is active",
        },
        "artifacts": {
            suffix: _sha256(output / f"{basename}.{suffix}")
            for suffix in ("script", "txt", "urp")
        },
        "controller_readback_verified": False,
        "live_authorized": False,
    }
    (output / f"{basename}.binding.json").write_text(json.dumps(binding, indent=2) + "\n", encoding="utf-8")
    return binding


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--basename", default=DEFAULT_BASENAME)
    parser.add_argument("--candidate-json", type=Path)
    args = parser.parse_args(argv)
    candidate = json.loads(args.candidate_json.read_text()) if args.candidate_json else {}
    result = build(args.output, basename=args.basename, candidate=candidate)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
