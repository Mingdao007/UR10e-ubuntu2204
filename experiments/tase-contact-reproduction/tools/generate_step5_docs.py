#!/usr/bin/env python3
"""Generate the compact Step5 operator flow from machine-readable v2 config."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "STEP5_FLOW.md"


def render(root: Path = ROOT) -> str:
    config = json.loads((root / "config/step5/current.json").read_text(encoding="utf-8"))
    deployment = config["deployment"]
    profile = config["execution_profile"]
    blocked = config["live_cutover"]["blocked_until"]
    blocker_lines = "\n".join(f"- `{value}`" for value in blocked) or "- none"
    return f"""<!-- GENERATED by tools/generate_step5_docs.py; do not hand-edit. -->
# Step5 current flow

## Current decision

Step5d native autotune v1 remains the accepted behavioral baseline. Control-plane
v2 is the maintained orchestration and production transport route. Its release
configuration is frozen and live cutover is enabled; this document still never
claims runtime READY without fresh bridge evidence.

The canonical Step5 pointer currently selects `{config['controller']['program']}`.

- Deployment: `{deployment['id']}`
- Controller program target: `{config['controller']['program']}`
- Static authorization: `{str(deployment['authorized']).lower()}`
- Controller readback verified: `{str(deployment['controller_readback_verified']).lower()}`
- Live cutover enabled: `{str(config['live_cutover']['enabled']).lower()}`

Fresh runtime truth comes only from:

```bash
step5d-autotune-live.sh status --json
```

`deployment_authorized` is static evidence. `runtime_ready` is a fresh service
observation. `status --json` opens the existing SQLite database read-only and
fails closed if it is missing or corrupt. Missing or stale status is never READY.

## Control boundary

The v2 package owns orchestration, persistence, transport, recovery, and
reporting. It does not change the frozen RNN, trajectory, force/frame math,
units, command order, or safety guards.

| Contract | Frozen value |
|---|---:|
| normal rate | `{profile['normal_max_rate_rad_s']}` rad/s |
| host qdot slew | `{profile['host_qdot_slew_rad_s2']}` rad/s² |
| TP speedj acceleration | `{profile['tp_speedj_accel_rad_s2']}` rad/s² |
| qdot cap | `{profile['qdot_cap_rad_s']}` rad/s |

Force semantics remain: `reaction_normal` measures positive load and
`approach_normal = -reaction_normal` defines posture/press direction.

## Inherited Local Control Textbook Alignment

The compact Step5d route does not replace the wider Step5 control contract:

- canonical textbook: `config/local_control_textbook_spec.json`;
- Step5a contract: `config/step5a_local_control_spec.json`;
- Step5a TP v3 script: `programs/step5/step5a_cycloid_no_contact_v3.script`;
- Step5b source: `programs/step5/step5b_contact_cycloid_baseline_v1.script`;
- safe-frame evidence: `config/step5_safe_frame.json`.

## Physical lifecycle

1. Persist ARM in SQLite.
2. Bind ARM to the deployment-derived `nf050-slew050-a050` profile and publish
   one atomic mailbox snapshot.
3. Observe exact TP consumption and mark the tuple physically attempted.
4. Observe RUN, retract, return, and measured Home verification.
5. Seal the minimum immutable raw capture.
6. Persist and publish ACK.
7. Observe READY_HOME and close the physical lifecycle.
8. Run metrics, PNG, and transfer as postprocess.

Postprocess cannot delay ACK. A postprocess failure pauses at safe Home and
never authorizes an automatic repeat. Ambiguous TP consumption is recorded as
`uncertain_attempt` and is also never repeated.

READY additionally requires the exact bridge PID/launch nonce plus a fresh,
progressing `step5d.autotune.bridge-health/v2` sidecar. The service checks it
before every host heartbeat and with a 100 ms child watcher. Loss revokes READY
and quarantines an open physical trial in one SQLite transaction.

## Parameter batches

- A normal append contains exactly five new physical tuples.
- P/D use a log2 lattice with 0.25-octave steps.
- I coarse search uses exactly `10×, 50×, 100×, 500×, 1000×`, then log2 refinement.
- Parameter append changes neither deployment/code fingerprint nor service process.
- Caller-supplied profile IDs must equal the canonical deployment-derived ID.
- Explicit replay has a nonce and purpose and is excluded from optimizer/incumbent history.

The imported recovery batch is G11–G15. G11 is complete; only G12–G15 remain
pending. G10 original diagnostic evidence is the historical incumbent. Video
replays do not replace it.

```bash
step5d-autotune-live.sh enqueue --file batch.json
step5d-autotune-live.sh report --batch latest --format markdown
step5d-autotune-live.sh replay --group G10 --reason video
step5d-autotune-live.sh stop-after-current
```

Every trial report contains exactly two tables: group/parameter mapping and
one-metric-per-row comparison against a same-deployment/profile incumbent, or
the explicitly labeled read-only G10 historical diagnostic reference. Startup
reconciles current-deployment COMPLETE trials that lost their report crash cut.

## Service and operator sequence

The systemd user service owns the complete bridge process tree with
`Restart=no` and one live-writer lease. Starting from a terminal or Codex
session must not bind process lifetime to that terminal.

When every live gate is complete:

1. Run `step5d-autotune-live.sh` once.
2. Wait for fresh `runtime_ready=true` with configured 500 Hz and progressing
   bridge-health evidence.
3. Press TP Play once.
4. Let the service advance distinct pending candidates.

No bridge start, TP Play, load, motion, zero/tare, or controller write is
authorized by this document.

## Live-cutover blockers

{blocker_lines}

The controller triplet must be fetched before building TP v2 so the user's
current waypoint is preserved. TP v2 may change only handshake/watchdog
identity. The diff gate requires the exact reviewed block in `.script` and its
exact XML-escaped representation in decompressed `.urp`; upload then requires
fresh readback.

## Source of truth

- Static deployment: `config/step5/current.json`
- Dynamic runtime/campaign: ignored SQLite DB under `runs/step5d_autotune_v2/`
- Stage manifests: `config/step5/stages/index.json`
- Legacy evidence mapping: `config/step5/autotune_legacy_map_v1.json`
- Archived long-form docs: `docs/archive/step5/INDEX.md`

`config/current_stage.json` and `config/step5_stage_table.json` are synchronized
compatibility mirrors for the current v2 binding. `config/step5d/current.json`
remains a frozen v1 compatibility input and is not v2 runtime truth.
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = args.root / "STEP5_FLOW.md"
    expected = render(args.root)
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != expected:
            raise SystemExit("STEP5_FLOW.md is stale; run tools/generate_step5_docs.py")
        return 0
    output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
