#!/usr/bin/env python3
"""Hard line caps and no-prose-runtime gates for canonical Step5 files."""

from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def lines(path: Path) -> int:
    return len(path.read_bytes().splitlines())


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--handoff", type=Path, action="append", default=[])
    args = parser.parse_args()
    root = args.root.resolve()
    limits = {
        root / "README.md": 200,
        root / "STEP5_FLOW.md": 200,
        root / "config/step5/current.json": 100,
    }
    failures = []
    for path, maximum in limits.items():
        count = lines(path)
        if count > maximum:
            failures.append(f"{path}: {count}>{maximum}")
    flow = (root / "STEP5_FLOW.md").read_text(encoding="utf-8")
    if not flow.startswith("<!-- GENERATED by tools/generate_step5_docs.py"):
        failures.append("STEP5_FLOW.md is not a generated view")
    forbidden = (
        "STEP5_FLOW.md",
        "config/current_stage.json",
        "config/step5_stage_table.json",
        "config/step5d/current.json",
    )
    for path in (root / "tools/step5d_autotune_v2").glob("*.py"):
        text = path.read_text(encoding="utf-8")
        for token in forbidden:
            if token in text:
                failures.append(f"v2 runtime parses legacy/prose source: {path.name}:{token}")
    for handoff in args.handoff:
        if lines(handoff) > 120:
            failures.append(f"new handoff exceeds 120 lines: {handoff}")
    if failures:
        raise SystemExit("\n".join(failures))
    print("step5_doc_contract=pass")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
